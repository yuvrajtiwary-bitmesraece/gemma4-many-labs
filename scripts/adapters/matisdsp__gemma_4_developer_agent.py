SCREENING = r"^docs/paper/records/screening_attempts\.csv$"
LEDGER = r"^reports/ledger\.jsonl$"
LEDGER_RUNS = {  # ledger entry -> (system, run); only entries that publish a per-task outcome map of one execution
    "e4b-calibration": ("e4b@kaggle", "kaggle/e4b-calibration"),
    "modal-e4b-pilot2": ("e4b@modal", "modal/e4b-pilot2"),
}
C6_LOG = r"^reports/2026-10-22_eval_c6_partial\.log$"
C6_LINE = re.compile(r"^\[\s*[\d.]+ min\]\s+\d+/\d+\s+(\S+)\s+(\S+)\s+r(\d+)\s+resolved=(True|False)\s+patch=\d+\s+"
                     r"calls=\d+\s+agent=[\d.]+s\s+wall=[\d.]+s\s*(.*)$")
GOLD_OK = "reports/gold_ok.txt"


def attempts(src):
    # 1. the pre-registered screening: one record per attempt
    for path, rows in src.csv(SCREENING):
        for row in rows:
            y = int(row["resolved"].strip() == "True")
            error = (row.get("error") or "").strip()
            yield {
                "file": path,
                "system": f"screening/{row['variant']}",
                "run": f"screening/{row['variant']}/rep{row['rep']}",
                "task": row["task"].strip(),
                "y": y,
                "model": "E4B",
                "harness": "official",
                "err": bool(error),
                "status": error or ("resolved" if y else "failed"),
            }
    # 2. two early E4B runs whose per-task outcomes are in the run ledger
    for path, entries in src.jsonl(LEDGER):
        for entry in entries:
            if entry.get("run") not in LEDGER_RUNS or not isinstance(entry.get("per_task"), dict):
                continue
            system, run = LEDGER_RUNS[entry["run"]]
            for task, resolved in entry["per_task"].items():
                yield {
                    "file": path,
                    "system": system,
                    "run": run,
                    "task": task,
                    "y": int(bool(resolved)),
                    "model": "E4B",
                    "harness": "official",
                    "err": None,
                    "status": "resolved" if resolved else "failed",
                }
    # 3. the finished jobs of the aborted 31B kernel eval-c6 (gold-scorable tasks only)
    gold_ok = set(src.text(GOLD_OK).split())
    for path, raw in src.read_many(C6_LOG):
        for line in raw.decode("utf-8", "replace").splitlines():
            m = C6_LINE.match(line.strip())
            if not m:
                continue
            variant, task, rep, resolved, error = m.groups()
            if task not in gold_ok:
                continue
            y = int(resolved == "True")
            yield {
                "file": path,
                "system": f"{variant}@kaggle-c6-aborted",
                "run": f"kaggle/eval-c6/{variant}/rep{rep}",
                "task": task,
                "y": y,
                "model": "31B",
                "harness": "official",
                "err": bool(error.strip()),
                "status": error.strip() or ("resolved" if y else "failed"),
            }
