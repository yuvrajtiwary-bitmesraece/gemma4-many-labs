"""Write results/RESULTS.md: every reported number, generated from results.json.

Nothing in the report is typed by hand, so the text cannot drift from the
analysis output.

    python scripts/report.py [results_dir]
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def p(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def f(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def read_csv(path: Path):
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def main(argv) -> int:
    results = Path(argv[0]) if argv else ROOT / "results"
    r = json.loads((results / "results.json").read_text(encoding="utf-8"))
    tables = results / "tables"
    derived = ROOT / "data" / "derived"
    d, p1, p2, p2b, p3, p4 = r["data"], r["P1"], r["P2"], r["P2b"], r["P3"], r["P4"]
    L = []
    L.append("# Results\n")
    L.append("Generated by `scripts/report.py` from `results/results.json`. Analyses P1-P4 and the robustness "
             "checks were fixed in `ANALYSIS_PLAN.md` before any outcome file was opened; `DEVIATIONS.md` lists "
             "every later change. Analyses marked *exploratory* were not fixed in advance.\n")

    scr = derived / "screening_summary.json"
    if scr.exists() and not argv:
        s = json.loads(scr.read_text(encoding="utf-8"))
        L.append("## Sources\n")
        L.append(table([
            ["Repositories returned by the six searches", s["candidates"]],
            ["Fetched at a pinned commit (the rest: " + ", ".join(f"{v} {k}" for k, v in s["not_fetched"].items()) + ")", s["fetched"]],
            ["... containing development-set task identifiers", s["with_dev_task_ids"]],
            ["... and an explicit licence that permits reuse", s["of_those_licensed"]],
            ["... and at least one eligible run (used)", s["used"]],
        ], ["Stage", "Repositories"]))
        L.append("\nLicences of the sources used: " + ", ".join(f"{k} ({v})" for k, v in sorted(s["licences_of_used"].items())) +
                 ". Every candidate and the stage at which it left the study is listed in `data/derived/screening.csv`.\n")

    L.append("## Pooled data\n")
    L.append(table([
        ["Attempts (one agent run on one task, binary outcome)", f"{d['n_attempts']:,}"],
        ["Labs (GitHub accounts)", d["n_labs"]],
        ["Systems (agent configurations)", d["n_systems"]],
        ["Runs", d["n_runs"]],
        ["Development-set tasks covered", d["n_tasks"]],
        ["Runs covering all 129 tasks", d["run_size"]["n_full_129"]],
        ["Distinct task subsets used by runs", d["n_distinct_task_sets"]],
        ["Tasks per run (min / median / max)", f"{d['run_size']['min']} / {d['run_size']['median']:.0f} / {d['run_size']['max']}"],
        ["Labs per task (min / median / max)", f"{d['labs_per_task']['min']} / {d['labs_per_task']['median']:.0f} / {d['labs_per_task']['max']}"],
        ["Systems with repeated runs", f"{d['n_systems_with_replicates']} in {d['n_labs_with_replicates']} labs"],
        ["Resolve rate, all attempts", p(d["raw_resolve_rate"])],
        ["Resolve rate, lab-balanced (systems within lab, then labs)", p(d["lab_balanced_resolve_rate"])],
    ], ["Quantity", "Value"]))
    L.append("\nRuns by model size: " + ", ".join(f"{k} {v}" for k, v in d["runs_by_model"].items()) +
             ". Runs by scorer: " + ", ".join(f"{k} {v}" for k, v in d["runs_by_harness"].items()) + ".\n")
    labs = read_csv(tables / "labs.csv")
    L.append(table([[x["code"], x["n_systems"], x["n_runs"], x["n_attempts"], x["n_tasks"], x["models"], x["harness"],
                     p(float(x["mean_system_rate"]))] for x in labs],
                   ["Lab", "Systems", "Runs", "Attempts", "Tasks", "Models", "Scorer", "Mean system resolve rate"]))
    L.append("\nLab codes are assigned by decreasing number of attempts. The mapping to sources is in "
             "`data/derived/sources.csv` and `results/tables/labs.csv`.\n")

    sh = p1["split_half"]
    L.append("## P1. Consensus on task difficulty\n")
    L.append(f"- Tasks attempted by at least 5 labs: **{p1['n_tasks_5_labs']}** of {p1['n_tasks_any']}.")
    L.append(f"- Split-half reliability of consensus difficulty (Spearman, {sh.get('n_valid')} random splits of the "
             f"labs): median **{f(sh.get('median'))}** (2.5-97.5 percentile {f(sh.get('p2.5'))} to {f(sh.get('p97.5'))}), "
             f"Spearman-Brown corrected **{f(sh.get('spearman_brown'))}**; median {sh.get('median_tasks_used', 0):.0f} tasks per split.")
    pw = p1.get("pairwise", {})
    L.append(f"- Pairwise agreement between labs sharing at least 30 tasks: {pw.get('n_pairs_defined')} pairs, median "
             f"Spearman {f(pw.get('median'))} (interquartile range {f(pw.get('q25'))} to {f(pw.get('q75'))}, "
             f"minimum {f(pw.get('min'))}, maximum {f(pw.get('max'))}).")
    L.append(f"- Floor (consensus solve rate at most 10%): **{p1['floor_tasks']}** tasks, of which "
             f"{p1['zero_everywhere_tasks']} were never resolved by any lab. Ceiling (at least 90%): "
             f"**{p1['ceiling_tasks']}**. Discriminating (in between): **{p1['discriminating_tasks']}**.")
    q = p1.get("d_quantiles", {})
    L.append(f"- Consensus solve rate: mean {p(p1.get('d_mean'))}, median {p(q.get('0.5'))}, quartiles {p(q.get('0.25'))} "
             f"and {p(q.get('0.75'))}.\n")

    L.append("## P2. Variance decomposition\n")
    rows = []
    for key, name in (("lab_balanced", "Lab-balanced"), ("unweighted", "Unweighted")):
        m = p2[key]
        rows.append([name, p(m.get("r2_task")), p(m.get("r2_lab")), p(m.get("r2_system")), p(m.get("r2_task_plus_system")),
                     p(m.get("r2_system_given_task")), p(m.get("r2_task_given_system"))])
    L.append("In-sample R² of linear probability models on all attempts:\n")
    L.append(table(rows, ["Weights", "Task", "Lab", "System", "Task + system", "System after task", "Task after system"]))
    nb, nu = p2["replicate_noise_lab_balanced"], p2["replicate_noise_unweighted"]
    sb = p2["saturated_lab_balanced"]
    L.append(f"\nOn the {nb.get('n_cells')} system × task cells with repeated runs ({nb.get('n_attempts')} attempts), the "
             f"unbiased within-cell variance is {f(nb.get('noise_variance'), 4)} of a total {f(nb.get('total_variance'), 4)}: "
             f"run-to-run noise accounts for **{p(nb.get('noise_share'))}** of outcome variance (lab-balanced; "
             f"{p(nu.get('noise_share'))} unweighted). The saturated system × task model fits "
             f"{p(sb.get('r2_saturated_in_sample'))} in-sample on the same cells, which overstates the explained share "
             f"because cell means absorb part of the noise.\n")

    L.append("## P2b. Within-lab generalizability study\n")
    if p2b.get("n_labs"):
        g = read_csv(tables / "g_study.csv")
        L.append(table([[x["code"], x["n_systems"], x["n_tasks"], x["n_replicates"], p(float(x["share_task"])),
                         p(float(x["share_system"])), p(float(x["share_system_x_task"])), p(float(x["share_replicate"])),
                         f(float(x["g_n129_k1"])), f(float(x["g_n129_k3"])), p(float(x["se_diff_n129"]))] for x in g],
                       ["Lab", "Systems", "Tasks", "Repeats", "Task", "System", "System × task", "Run-to-run",
                        "Eρ² (129 tasks, 1 run)", "Eρ² (129 tasks, 3 runs)", "SE of a difference (129 tasks, 1 run)"]))
        rows = []
        for n in (30, 60, 129):
            rows.append([n] + [f"{f(p2b[f'g_n{n}_k{k}']['median'])} ({f(p2b[f'g_n{n}_k{k}']['min'])}-{f(p2b[f'g_n{n}_k{k}']['max'])})"
                               for k in (1, 3, 5)] +
                        [f"{p(p2b[f'se_diff_n{n}']['median'])} ({p(p2b[f'se_diff_n{n}']['min'])}-{p(p2b[f'se_diff_n{n}']['max'])})"])
        L.append(f"\nAcross the {p2b['n_labs']} labs with a balanced block (median, range):\n")
        L.append(table(rows, ["Tasks", "Eρ², 1 run", "Eρ², 3 runs", "Eρ², 5 runs", "SE of the difference of two systems, 1 run each"]))
        L.append(f"\nMedian shares: task {p(p2b['share_task']['median'])}, system {p(p2b['share_system']['median'])}, "
                 f"system × task {p(p2b['share_system_x_task']['median'])}, run-to-run {p(p2b['share_replicate']['median'])}.\n")
    else:
        L.append("No lab had a balanced block of at least 2 systems, 20 tasks and 2 repeats.\n")

    L.append("## P3. Replicate noise and detectable differences\n")
    fr, ad, pl = p3["flip_rate"], p3["abs_score_diff"], p3.get("pair_level", {})
    if fr.get("n_pairs"):
        L.append(f"- {fr['n_pairs']} pairs of repeated runs, {fr['n_systems']} systems, {fr['n_labs']} labs; median "
                 f"{pl.get('median_shared_tasks', 0):.0f} shared tasks per pair.")
        L.append(f"- **Flip rate** (share of shared tasks whose outcome differs between two repeats): pooled "
                 f"**{p(fr['pooled'])}**; across labs median {p(fr['lab_median'])}, interquartile range "
                 f"{p(fr['lab_q25'])} to {p(fr['lab_q75'])}, range {p(fr['lab_min'])} to {p(fr['lab_max'])}.")
        L.append(f"- Absolute difference in resolve rate between two repeats: pooled {p(ad['pooled'])}; across labs "
                 f"median {p(ad['lab_median'])}, range {p(ad['lab_min'])} to {p(ad['lab_max'])}; largest single pair "
                 f"{p(pl.get('abs_diff_max'))}; {p(pl.get('share_identical_runs'))} of pairs had identical outcomes on every task.")
        mdd = p3.get("mdd_pooled_flip", {})
        L.append("- Minimum detectable improvement for one paired comparison (exact two-sided McNemar test, α = 0.05, "
                 "power 0.80, discordance = flip rate + improvement): " +
                 ", ".join(f"**{p(mdd.get(str(n)), 1)}** on {n} tasks" for n in (30, 60, 129)) + ".")
        cc = p3.get("consistency_check", {})
        L.append(f"- Consistency check fixed in advance: pooled flip rate {p(cc.get('pooled_flip_rate'))} against twice "
                 f"the replicate-noise variance {p(cc.get('twice_noise_variance_unweighted'))} (unweighted).\n")
    else:
        L.append("No pair of repeated runs shared at least 10 tasks.\n")

    L.append("## P4. Subset comparability\n")
    pr = p4["predicted_rate"]
    mc = p4["model_check"]
    L.append(f"- Rasch model on {p4['n_systems']} systems and {p4['n_tasks']} tasks (converged: {p4['converged']}). "
             f"Reference system: median ability among the {p4['n_31B_systems']} systems labelled 31B.")
    L.append(f"- Runs used **{p4['n_distinct_subsets']}** distinct task subsets of at least 10 tasks. Predicted resolve "
             f"rate of the reference system: **{p(pr['min'])} to {p(pr['max'])}** (range {p(pr['range'])} points; "
             f"interquartile range {p(pr['q25'])} to {p(pr['q75'])}); on the full task set {p(p4['predicted_full_task_set'])}.")
    if "predicted_rate_subsets_30plus" in p4:
        s30 = p4["predicted_rate_subsets_30plus"]
        L.append(f"- Restricted to the {s30['n']} subsets of at least 30 tasks: {p(s30['min'])} to {p(s30['max'])}.")
    L.append(f"- Model check (not fixed in advance): predicted against observed resolve rate per run, Pearson "
             f"{f(mc['run_level_pearson'])}, mean absolute error {p(mc['run_level_mean_abs_error'])}; Brier score "
             f"{f(mc['attempt_level_brier'], 3)} against {f(mc['attempt_level_brier_base_rate'], 3)} for the base rate.\n")

    L.append("## Exploratory analyses\n")
    e2 = r["E2_model_size"]
    L.append("**E2. Model size.** Mean Rasch ability over labs (lab-clustered bootstrap, model not refitted):\n")
    L.append(table([[k, v["n_labs"], v["n_systems"], f(v["mean_theta_over_labs"]),
                     "n/a" if not v.get("ci95") else f"{f(v['ci95'][0])} to {f(v['ci95'][1])}", p(v["mean_raw_rate_over_labs"])]
                    for k, v in sorted(e2["by_model"].items())],
                   ["Model", "Labs", "Systems", "Mean ability", "95% interval", "Mean raw resolve rate"]))
    if e2["within_lab_contrasts"]:
        L.append("\nWithin-lab contrasts on shared tasks:\n")
        L.append(table([[c["lab"], c["model_a"], p(c["rate_a"]), c["model_b"], p(c["rate_b"]), c["n_shared_tasks"]]
                        for c in e2["within_lab_contrasts"]], ["Lab", "Model A", "Rate A", "Model B", "Rate B", "Shared tasks"]))
    L.append("\n**E3. Source library.** Consensus solve rate by library (tasks attempted by at least 5 labs):\n")
    L.append(table([[k, v["n_tasks"], p(v["mean_d"]), p(v["median_d"]), p(v["share_floor"])] for k, v in sorted(r["E3_repo"].items())],
                   ["Library", "Tasks", "Mean", "Median", "Share at the floor"]))
    e4 = r["E4_instability"]
    if e4.get("n_tasks", 0) >= 5:
        L.append(f"\n**E4. Instability by difficulty.** On {e4['n_tasks']} tasks with repeated runs in at least 2 labs, "
                 f"replicate disagreement tracks the binomial expectation 2d(1-d) (Spearman "
                 f"{f(e4['spearman_flip_vs_binomial'])}); observed disagreement is {f(e4['ratio_observed_to_binomial'])} "
                 f"times that expectation. The {e4['n_discriminating']} discriminating tasks carry "
                 f"{p(e4['share_of_total_flip_in_discriminating'])} of all disagreement (mean {p(e4['mean_flip_discriminating'])} "
                 f"per task, against {p(e4['mean_flip_floor'])} for floor tasks).\n")
    L.append("\n**E1. Development set versus leaderboard** was not carried out: see `DEVIATIONS.md`.\n")
    for key in sorted(k for k in r if k.startswith("X")):
        L.append(f"**{key}.** `results.json` -> `{key}`.\n")

    L.append("## Robustness checks\n")
    rb = r["robustness"]
    rows = []
    names = {"all": "All data", "model_31B_only": "31B systems only", "official_harness_only": "Official harness only",
             "drop_error_flagged": "Dropping attempts with an error flag"}
    for key, name in names.items():
        c = rb.get(key, {})
        if "note" in c:
            rows.append([name, c.get("n_labs"), f"{c.get('n_attempts'):,}", "too few labs", "", "", "", "", ""])
            continue
        rows.append([name, c.get("n_labs"), f"{c.get('n_attempts'):,}", f(c.get("split_half_median")),
                     f"{c.get('floor_tasks')} / {c.get('discriminating_tasks')} / {c.get('ceiling_tasks')}",
                     p(c.get("r2_task")), p(c.get("noise_share")), p(c.get("flip_pooled")), p(c.get("mdd_129"))])
    L.append(table(rows, ["Subset", "Labs", "Attempts", "Split-half ρ", "Floor / discriminating / ceiling", "R² task",
                          "Noise share", "Pooled flip rate", "Detectable on 129 tasks"]))
    lo = rb["leave_one_lab_out"]
    L.append(f"\nLeave-one-lab-out: split-half reliability {f(lo['split_half_median']['min'])} to "
             f"{f(lo['split_half_median']['max'])}; pooled flip rate {p(lo['flip_pooled']['min'])} to "
             f"{p(lo['flip_pooled']['max'])}; floor tasks {lo['floor_tasks']['min']} to {lo['floor_tasks']['max']}. "
             f"Per-lab values are in `results/tables/leave_one_lab_out.csv`.\n")
    L.append("## Tables and figures\n")
    L.append("- `results/tables/tasks.csv`: per task, consensus solve rate, number of labs, class, Rasch difficulty, "
             "replicate disagreement.\n- `results/tables/lab_task_matrix.csv`: lab-level solve rate per task.\n"
             "- `results/tables/replicate_pairs.csv`, `g_study.csv`, `subset_predictions.csv`, `systems.csv`, "
             "`pairwise_lab_spearman.csv`, `leave_one_lab_out.csv`, `mdd_curve.csv`.\n"
             "- `paper/figures/fig1..fig5`: drawn by `scripts/figures.py` from the tables above.\n")
    (results / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", results / "RESULTS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
